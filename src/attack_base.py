"""
Attack Module Base — Layer 2 foundation.

Defines the interface all attack modules must implement.
Modules receive the probe engine as a dependency and emit Finding objects.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any

from src.models import Finding
from src.probe_engine import ProbeEngine


class AttackModule(ABC):
    """
    Base class for all attack modules.

    Subclasses must implement:
        - name: human-readable module name
        - surface: attack surface identifier (e.g. "D - Data Flow & Exfiltration")
        - module_id: short ID (e.g. "D1")
        - description: what this module tests and why
        - run(): execute the attack and return findings
    """

    name: str
    surface: str
    module_id: str
    description: str

    def __init__(self, engine: ProbeEngine) -> None:
        self.engine = engine
        self.findings: list[Finding] = []
        self._finding_counter: int = 0

    def _next_finding_id(self) -> str:
        """Generate sequential finding ID like D1-001, D1-002."""
        self._finding_counter += 1
        return f"{self.module_id}-{self._finding_counter:03d}"

    def add_finding(self, finding: Finding) -> None:
        """Validate and store a finding."""
        # Pydantic validation happens at construction time.
        # This method is the single entry point for all findings.
        self.findings.append(finding)

    def get_phase0_context(self) -> dict[str, Any]:
        """Return Phase 0 analyzer context shared by the scanner."""
        return self.engine.shared_context.get("phase0", {})

    def get_attack_targets(self, min_severity: str | None = None) -> list[dict[str, Any]]:
        """
        Return prioritized attack targets generated by the blueprint analyzer.
        """
        phase0 = self.get_phase0_context()
        attack_map = phase0.get("attack_map", {})
        targets = attack_map.get("targets", [])
        if not min_severity:
            return targets
        by_severity = attack_map.get("by_severity", {})
        return by_severity.get(min_severity, [])

    @abstractmethod
    async def run(self) -> list[Finding]:
        """
        Execute the attack module.

        Must be called inside an active engine.connect() context.
        Returns list of validated Finding objects.
        """
        ...

    def summary(self) -> dict[str, Any]:
        """Quick summary for reporting."""
        return {
            "module": self.module_id,
            "name": self.name,
            "surface": self.surface,
            "findings_count": len(self.findings),
            "severities": {
                s: sum(1 for f in self.findings if f.severity.value == s)
                for s in ["Critical", "High", "Medium", "Low", "Info"]
                if any(f.severity.value == s for f in self.findings)
            },
        }
